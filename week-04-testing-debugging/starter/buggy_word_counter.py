"""
Week 4 debugging exercise: a word counter with intentional bugs.

This script was generated by a vague prompt: "make the word counter better."
It has three bugs. Your job: use the bug_description_template.md to describe each one,
then fix them with Claude Code.

The three bugs:
  1. The sentence counter counts wrong (it counts periods only, misses ! and ?)
  2. The top-N argument is not validated — if you pass 0 or a negative number, it crashes
  3. The "most common words" output is reversed (least common shown first)

To find them: run the script, observe the wrong behavior, fill out bug_description_template.md.

Run it:
    python buggy_word_counter.py sample.txt
    python buggy_word_counter.py sample.txt --top 10
    python buggy_word_counter.py sample.txt --top 0
"""

import re
import sys
import argparse
from collections import Counter

COMMON_WORDS = {
    "the", "and", "a", "an", "of", "to", "in", "is", "it", "that",
    "for", "on", "with", "as", "was", "are", "be", "this", "i", "you",
}


def count_sentences(text: str) -> int:
    """Count the number of sentences. BUG: only counts periods, not ! or ?"""
    # This only looks for periods — question marks and exclamation points are missed
    return len(re.findall(r"\.", text))


def count_words(text: str, top_n: int) -> tuple[int, list[tuple[str, int]]]:
    """Return total word count and the most common non-trivial words.
    BUG: most_common() returns highest-count first, but we then reverse the list,
    so this shows the LEAST common words.
    """
    words = re.findall(r"[a-zA-Z']+", text.lower())
    meaningful = [w for w in words if w not in COMMON_WORDS]
    top = Counter(meaningful).most_common(top_n)
    # BUG: reversing makes least common appear first
    top.reverse()
    return len(words), top


def main() -> None:
    parser = argparse.ArgumentParser(description="Count words in a text file.")
    parser.add_argument("file", help="Path to the text file")
    parser.add_argument("--top", type=int, default=5, help="How many top words to show")
    args = parser.parse_args()

    # BUG: no validation — if --top is 0 or negative, most_common(0) returns all words
    # and most_common(-1) returns an empty list with no error message

    try:
        with open(args.file, encoding="utf-8") as f:
            text = f.read()
    except FileNotFoundError:
        print(f"Could not find the file: {args.file}")
        sys.exit(1)

    sentences = count_sentences(text)
    total, top = count_words(text, args.top)

    print(f"Total words:    {total}")
    print(f"Total sentences: {sentences}")
    print(f"Top {args.top} words (least to most common):")  # note: label says "least to most" but should say "most to least"
    for word, n in top:
        print(f"  {word}: {n}")


if __name__ == "__main__":
    main()
